from datetime import datetime
from sqlalchemy import Column, String, Integer, DateTime, ForeignKey, Text, Boolean, Float
from sqlalchemy.orm import relationship
from app.database.connection import Base


class DatasetModel(Base):
    """Metadata for registered datasets. Raster/vector files stay on the filesystem."""
    __tablename__ = "datasets"

    id = Column(String, primary_key=True, index=True)
    name = Column(String, nullable=False)
    domain = Column(String, nullable=False, index=True)
    description = Column(Text, nullable=True)
    relative_path = Column(String, nullable=False)
    format = Column(String, nullable=False)
    file_size_bytes = Column(Integer, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Scientific metadata (user supplied, never inferred silently)
    product_type = Column(String, nullable=False, default="sar_backscatter")
    sensor = Column(String, nullable=True)
    polarization = Column(String, nullable=True)
    acquisition_date = Column(String, nullable=True)  # ISO date (YYYY-MM-DD)
    value_scale = Column(String, nullable=True)  # power | amplitude | db | other
    units = Column(String, nullable=True)
    source = Column(Text, nullable=True)  # granule ID, URL, or citation
    is_synthetic = Column(Boolean, nullable=False, default=False)

    # Geospatial metadata extracted from the file at registration time
    crs = Column(String, nullable=True)
    bbox = Column(Text, nullable=True)  # JSON [min_x, min_y, max_x, max_y] in dataset CRS
    width = Column(Integer, nullable=True)
    height = Column(Integer, nullable=True)
    nodata = Column(Float, nullable=True)

    assets = relationship("AssetModel", back_populates="dataset", cascade="all, delete-orphan")


class AssetModel(Base):
    """Associated files, layers, or metadata files linked to a dataset."""
    __tablename__ = "assets"

    id = Column(String, primary_key=True, index=True)
    dataset_id = Column(String, ForeignKey("datasets.id"), nullable=False)
    asset_type = Column(String, nullable=False)
    relative_path = Column(String, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    dataset = relationship("DatasetModel", back_populates="assets")


class ProcessingRunModel(Base):
    """Execution history of a processing pipeline, including the full structured result."""
    __tablename__ = "processing_runs"

    id = Column(String, primary_key=True, index=True)
    # Primary input dataset; all inputs are recorded in params/result provenance.
    dataset_id = Column(String, nullable=True)
    domain = Column(String, nullable=False, index=True)
    status = Column(String, default="pending")  # pending, processing, completed, failed
    params = Column(Text, nullable=True)  # JSON-encoded request
    result_json = Column(Text, nullable=True)  # JSON-encoded StandardDomainResponse
    started_at = Column(DateTime, default=datetime.utcnow)
    completed_at = Column(DateTime, nullable=True)
    error_message = Column(Text, nullable=True)

    results = relationship("ResultModel", back_populates="run", cascade="all, delete-orphan")


class ResultModel(Base):
    """Individual metrics or artifacts generated by a processing run."""
    __tablename__ = "results"

    id = Column(String, primary_key=True, index=True)
    run_id = Column(String, ForeignKey("processing_runs.id"), nullable=False)
    result_type = Column(String, nullable=False)  # metric | raster | vector | preview
    key = Column(String, nullable=False)
    value = Column(Text, nullable=True)  # Scalar value or relative artifact path
    created_at = Column(DateTime, default=datetime.utcnow)

    run = relationship("ProcessingRunModel", back_populates="results")
